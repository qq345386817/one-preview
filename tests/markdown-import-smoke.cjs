const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.ONEPREVIEW_PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.ONEPREVIEW_SITE_URL || 'http://127.0.0.1:8765';
const output=process.env.ONEPREVIEW_SITE_QA_DIR || '/tmp/onepreview-site-qa';
fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true});
 try {
 const page=await browser.newPage({viewport:{width:1280,height:900}});const errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 page.on('request',r=>assert.equal(r.method(),'GET','Documents must never be uploaded'));
 await page.goto(base+'/tools/markdown-to-pdf/');
 const ready=()=>page.waitForFunction(()=>!document.querySelector('#print-report').disabled);
 await ready();const frame=page.frames().find(f=>f.url().endsWith('/report.html'));
 const source=page.locator('#markdown-source');const input=page.locator('#markdown-file');
 const words=await page.locator('#tool-messages').evaluate(e=>JSON.parse(e.textContent));
 const set=(name,content)=>input.setInputFiles({name,mimeType:'text/markdown',buffer:Buffer.from(content)});
 await set('Imported.MARKDOWN','# Imported\n\nFIRST-IMPORT');await ready();
 assert.match(await frame.locator('#report').innerText(),/FIRST-IMPORT/);
 assert.equal(await frame.title(),'Imported');
 await set('Imported.MARKDOWN','# Reimported\n\nSAME-FILE-UPDATED');await ready();
 assert.match(await frame.locator('#report').innerText(),/SAME-FILE-UPDATED/);
 const prior=await source.inputValue();await input.setInputFiles([]);assert.equal(await source.inputValue(),prior);
 await page.evaluate(()=>{window.realArrayBuffer=File.prototype.arrayBuffer;File.prototype.arrayBuffer=async function(){const result=await window.realArrayBuffer.call(this);await new Promise(r=>setTimeout(r,this.name==='slow.md'?200:10));return result;}});
 await set('slow.md','# Stale\n\nSHOULD-NOT-WIN');await set('latest.md','# Latest\n\nLATEST-IMPORT-WINS');await ready();
 await page.waitForTimeout(250);assert.equal(await source.inputValue(),'# Latest\n\nLATEST-IMPORT-WINS');
 assert.match(await frame.locator('#report').innerText(),/LATEST-IMPORT-WINS/);
 await set('slow.md','# Stale\n\nIGNORE-THIS-IMPORT');await source.fill('# Manual edit\n\nKEEP-MANUAL-EDIT');
 await page.waitForTimeout(250);assert.equal(await source.inputValue(),'# Manual edit\n\nKEEP-MANUAL-EDIT');
 assert.equal(await page.locator('#print-report').isDisabled(),true);
 await page.evaluate(()=>{File.prototype.arrayBuffer=window.realArrayBuffer;});
 await frame.evaluate(()=>{window.realRender=OnePreviewReport.render;OnePreviewReport.render=async(...args)=>{await new Promise(r=>setTimeout(r,180));return window.realRender(...args)}});
 await page.locator('#render-report').click();await set('after-busy.md','# After busy\n\nLATEST-RENDER-WINS');await ready();
 assert.match(await frame.locator('#report').innerText(),/LATEST-RENDER-WINS/);
 assert.equal(await frame.title(),'after-busy');
 await frame.evaluate(()=>{OnePreviewReport.render=window.realRender});
 const beforeFailure=await source.inputValue();
 await page.evaluate(()=>{File.prototype.arrayBuffer=async()=>{throw Error('UNLOCALIZED-LOW-LEVEL-ERROR')}});
 await set('unreadable.md','# Not readable');
 await page.waitForFunction(t=>document.querySelector('#report-status').textContent===t,words.read);
 assert.equal(await source.inputValue(),beforeFailure);
 assert.equal(await page.locator('#markdown-file-name').innerText(),words.selectedFile.replace('{name}','after-busy.md'));
 await page.evaluate(()=>{File.prototype.arrayBuffer=window.realArrayBuffer});
 assert.deepEqual(errors,[]);
 await page.screenshot({path:path.join(output,'import-races-desktop.png'),fullPage:false});
 console.log('Browser import races passed: keyboard picker is covered by locale suite; same-file reimport, cancel, latest-file-wins, edit-during-read, import-during-render, localized read failures and no uploads.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
